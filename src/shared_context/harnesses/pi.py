"""pi adapter: a pi extension that forwards lifecycle events to `ctx hook`,
plus a parser for pi's session JSONL format.

pi writes complete sessions to disk, so the extension stays thin: it only
signals when a session starts, when an agent turn ends, and when the session
shuts down. All analysis happens locally in Python against the session file.
"""

from __future__ import annotations

import json
from pathlib import Path

from ..analyzer import (
    MAX_TRANSCRIPT_BYTES,
    Signals,
    ToolRecorder,
    _iter_jsonl,
    add_usage,
    detect_restatement,
)
from ..install import ctx_argv
from .base import Harness

EXTENSION_NAME = "shared-context.ts"
PI_MARKER = "shared-context recorder"

# pi tool name -> canonical category (see analyzer.ToolRecorder)
PI_TOOL_CANON = {
    "read": "read",
    "ls": "read",
    "edit": "edit",
    "write": "edit",
    "multiedit": "edit",
    "bash": "bash",
    "grep": "search",
    "find": "search",
}


def extension_path() -> Path:
    return Path.home() / ".pi" / "agent" / "extensions" / EXTENSION_NAME


_EXTENSION_TEMPLATE = """/**
 * shared-context recorder - generated by `ctx init --harness pi`.
 *
 * Observe mode: forwards session lifecycle to the local ctx CLI over stdin.
 * No prompt text leaves the machine; `ctx report` reads aggregates only.
 * Remove with `ctx uninstall --harness pi`.
 */
import type { ExtensionAPI, ExtensionContext } from "@earendil-works/pi-coding-agent";
import { execFile } from "node:child_process";

const CTX_ARGV: string[] = __CTX_ARGV__;
const TIMEOUT_MS = 2500;

function forward(event: string, payload: Record<string, unknown>): void {
  try {
    const [bin, ...args] = CTX_ARGV;
    const child = execFile(bin, [...args, "hook", event], { timeout: TIMEOUT_MS }, () => {});
    child.stdin?.end(JSON.stringify(payload));
  } catch {
    // fail open: a recorder must never break the harness
  }
}

export default function (pi: ExtensionAPI) {
  const send = (event: string) => (_e: unknown, ctx: ExtensionContext) => {
    forward(event, {
      harness: "pi",
      session_id: ctx.sessionManager.getSessionId(),
      cwd: ctx.sessionManager.getCwd(),
      transcript_path: ctx.sessionManager.getSessionFile(),
    });
  };
  pi.on("session_start", send("session-start"));
  pi.on("agent_end", send("stop"));
  pi.on("session_shutdown", send("session-end"));
}
"""


def extension_source() -> str:
    return _EXTENSION_TEMPLATE.replace("__CTX_ARGV__", json.dumps(ctx_argv()))


def install_pi(mode: str) -> Path:
    if mode == "active":
        raise ValueError("pi integration is observe-only until context injection ships (Phase 1)")
    path = extension_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(extension_source())
    return path


def uninstall_pi() -> Path | None:
    path = extension_path()
    if not path.exists():
        return None
    try:
        text = path.read_text()
    except OSError:
        return None
    if PI_MARKER not in text:
        return None  # not ours: leave it alone
    path.unlink()
    return path


# ------------------------------------------------------------------- parsing


def _content_text(content) -> str:
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        return "\n".join(
            str(block.get("text") or "")
            for block in content
            if isinstance(block, dict) and block.get("type") == "text"
        )
    return ""


def active_chain(entries: list[dict]) -> list[dict]:
    """Entries on the current leaf-to-root path (pi sessions are trees).

    Abandoned branches must not inflate re-derivation: a path read only in a
    branch the user left is not context this session actually used.
    """
    messages = [e for e in entries if e.get("type") != "session"]
    by_id = {e["id"]: e for e in entries if isinstance(e.get("id"), str)}
    leaf = next((e for e in reversed(messages) if e.get("id") in by_id), None)
    if leaf is None:
        return messages  # legacy v1 sessions: no ids, file order is the order
    chain: list[dict] = []
    seen: set[str] = set()
    cur = leaf
    while cur is not None and isinstance(cur.get("id"), str) and cur["id"] not in seen:
        seen.add(cur["id"])
        chain.append(cur)
        parent = cur.get("parentId")
        cur = by_id.get(parent) if parent else None
    chain.reverse()
    if len(chain) < 0.5 * len(messages):
        return messages  # parent links too sparse to trust; degrade to file order
    return chain


def parse_pi_session(
    transcript_path: str | Path, root: str | None = None, cwd: str | None = None
) -> Signals:
    sig = Signals()
    path = Path(transcript_path)
    if not path.exists():
        return sig
    if path.stat().st_size > MAX_TRANSCRIPT_BYTES:
        return sig

    entries = [e for e in _iter_jsonl(path) if isinstance(e, dict)]
    rec = ToolRecorder(sig, root, cwd)
    prompt_index = 0

    for entry in active_chain(entries):
        etype = entry.get("type")
        if etype == "compaction":
            sig.compaction_count += 1
            continue
        if etype == "usage":
            # model-attributed usage outside assistant messages (e.g. cache warm)
            usage = entry.get("usage") or {}
            add_usage(
                sig,
                input_tokens=usage.get("input"),
                output_tokens=usage.get("output"),
                cache_read=usage.get("cacheRead"),
                cache_write=usage.get("cacheWrite"),
            )
            continue
        if etype != "message":
            continue

        message = entry.get("message") or {}
        role = message.get("role")

        if role == "user":
            text = _content_text(message.get("content"))
            # prompts starting with "<" are injected system-ish wrappers, not human input
            if text and not text.lstrip().startswith("<"):
                cls, conf = detect_restatement(text, prompt_index)
                sig.prompts += 1
                if cls:
                    sig.restatement_count += 1
                    sig.restatement_classes[cls] = sig.restatement_classes.get(cls, 0) + 1
                    sig.restatement_confidence = max(sig.restatement_confidence, conf)
                prompt_index += 1
            continue

        if role != "assistant":
            continue

        usage = message.get("usage") or {}
        add_usage(
            sig,
            input_tokens=usage.get("input"),
            output_tokens=usage.get("output"),
            cache_read=usage.get("cacheRead"),
            cache_write=usage.get("cacheWrite"),
        )
        for block in message.get("content") or []:
            if not isinstance(block, dict) or block.get("type") != "toolCall":
                continue
            canonical = PI_TOOL_CANON.get(str(block.get("name") or "").lower())
            if canonical:
                rec.record(canonical, block.get("arguments") or {}, entry.get("timestamp"))

    rec.finish()
    return sig


class PiHarness(Harness):
    name = "pi"
    label = "pi"
    doc_preference = "AGENTS.md"
    supports_active = False  # Phase 1: injection via pi.sendMessage

    def install(self, mode: str) -> list[Path]:
        return [install_pi(mode)]

    def uninstall(self) -> list[Path]:
        path = uninstall_pi()
        return [path] if path else []

    def is_installed(self) -> bool:
        path = extension_path()
        if not path.exists():
            return False
        try:
            return PI_MARKER in path.read_text()
        except OSError:
            return False

    def _parse(self, transcript: str | Path, root: str | None, cwd: str | None) -> Signals:
        return parse_pi_session(transcript, root, cwd)
